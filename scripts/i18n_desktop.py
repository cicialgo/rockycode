#!/usr/bin/env python
"""Export the desktop app's catalogs from rockycode/i18n/locales/*.toml.

One TOML file per language serves both surfaces: the terminal UI reads it
directly; the desktop (TypeScript, React) gets `apps/desktop/src/shared/catalog.ts`
from this script. Exported keys are the `desktop.*` section with the prefix
stripped, plus `capability_detail.*`, which the Python runtime sends to clients as
`detail_key` + `params`. Run it after editing a locale file; the catalog smoke
(tests/smoke_i18n_catalog.py) fails when the committed export is stale.

    python scripts/i18n_desktop.py          # writes the .ts file
    python scripts/i18n_desktop.py --check  # exit 1 when it would change
"""
from __future__ import annotations

import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCALES = ROOT / "rockycode" / "i18n" / "locales"
TARGET = ROOT / "apps" / "desktop" / "src" / "shared" / "catalog.ts"
SHARED_PREFIXES = ("capability_detail.",)


def _flatten(table: dict, prefix: str = "") -> dict[str, str]:
    out: dict[str, str] = {}
    for key, value in table.items():
        if isinstance(value, dict):
            out.update(_flatten(value, f"{prefix}{key}."))
        else:
            out[f"{prefix}{key}"] = str(value)
    return out


def exported(locale_file: Path) -> dict[str, str]:
    flat = _flatten(tomllib.loads(locale_file.read_text(encoding="utf-8")))
    out = {k[len("desktop."):]: v for k, v in flat.items() if k.startswith("desktop.")}
    out.update({k: v for k, v in flat.items() if k.startswith(SHARED_PREFIXES)})
    return out


def render(locales_dir: Path = LOCALES) -> str:
    files = sorted(locales_dir.glob("*.toml"))
    codes = ["en"] + sorted(p.stem for p in files if p.stem != "en")
    cats = {p.stem: exported(p) for p in files}
    lines = ["// GENERATED by scripts/i18n_desktop.py from rockycode/i18n/locales/*.toml — do not edit.",
             "// Edit the TOML (one file per language), rerun the script, commit both.",
             "/** UI text only. Never apply translations to prompts, model output or tool data. */"]
    for code in codes:
        lines.append(f"export const {code} = {{")
        lines += [f"  {json.dumps(k, ensure_ascii=False)}: {json.dumps(v, ensure_ascii=False)}," for k, v in cats[code].items()]
        lines.append("} as const" + (";" if code == "en" else " satisfies Record<keyof typeof en, string>;"))
    lines.append("export const catalogs = {" + ", ".join(codes) + "} as const;")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print(f"{TARGET.relative_to(ROOT)} is stale — run python scripts/i18n_desktop.py", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
